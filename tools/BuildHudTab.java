        g.setColor(new Color(0x3d5c3a)); g.fillRect(0, gh * scale / 2, gw * scale, gh * scale / 2);
        g.setColor(new Color(0, 0, 0, 102)); g.fillRect((left - 2) * scale, (headerY - 10) * scale, (right - left + 2) * scale, 9 * scale);
