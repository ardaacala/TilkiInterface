        int biggest = 0;
        for (String[] line : lines) biggest = Math.max(biggest, BuildShared.width(line[1]) + (line[0] != null ? 14 : 0));
        int count = lines.length, bottom = gh / 2 + count * 9 / 3, headerY = bottom - count * 9, left = gw - biggest - 3, right = gw - 1;
