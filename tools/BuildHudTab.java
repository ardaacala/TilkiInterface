    static void put(Graphics2D g, String key, int x, int y, int ox, int scale) throws IOException {
        BufferedImage image = ImageIO.read(TEXTURES.resolve("hud/" + key + ".png").toFile());
        g.drawImage(image, ox + x * scale, y * scale, image.getWidth() * scale, image.getHeight() * scale, null);
    }
    static void tile(Graphics2D g, String key, int from, int to, int y, int ox, int scale) throws IOException {
        BufferedImage image = ImageIO.read(TEXTURES.resolve("hud/" + key + ".png").toFile());
        for (int x = from; x < to; x += image.getWidth()) put(g, key, Math.min(x, to - image.getWidth()), y, ox, scale);
    }
    static void centered(Graphics2D g, String text, int cx, int y, int ox, int scale, int rgb) {
        int x = cx - BuildShared.width(text) / 2;
        BuildShared.drawText(g, text, ox + (x + 1) * scale, (y + 1) * scale, scale, 0x3f3f3f);
        BuildShared.drawText(g, text, ox + x * scale, y * scale, scale, rgb);
    }
