$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path $PSScriptRoot -Parent
$root = Join-Path $projectRoot 'resourcepack'
Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.IO.Compression.FileSystem
foreach ($file in (Get-ChildItem $root -Recurse -File | Where-Object { $_.Extension -eq '.json' -or $_.Extension -eq '.mcmeta' })) {
    $null = [IO.File]::ReadAllText($file.FullName) | ConvertFrom-Json
}
$meta = [IO.File]::ReadAllText((Join-Path $root 'pack.mcmeta')) | ConvertFrom-Json
if ($meta.pack.min_format -ne 46 -or $meta.pack.max_format -ne 999 -or $meta.overlays) { throw 'pack.mcmeta must cover 46..999 without overlays' }
$font = [IO.File]::ReadAllText((Join-Path $root 'assets/tilkiinterface/font/ui.json')) | ConvertFrom-Json
# UI v3: everything generated by tools/BuildUiV3.java from art/source lives in font/v3.
$icons=@($font.providers | Where-Object { $_.type -eq 'bitmap' -and $_.file -like 'tilkiinterface:font/v3/icon_*' })
if($icons.Count -ne 8 -or ($icons | Where-Object { $_.height -ne 9 -or $_.ascent -ne 8 })) { throw 'Stat icons must be eight one-line glyphs' }
if($font.providers | Where-Object { $_.file -match 'tilkiinterface:font/(hud|esc_menu)/|sidebar_logo|esc_frame\.png' }) { throw 'Screenshot-derived v2 glyphs remain' }
$codes=@{}
foreach ($provider in $font.providers) {
    if ($provider.type -ne 'bitmap') { continue }
    if ($provider.ascent -gt $provider.height) { throw "Ascent above height: $($provider.file)" }
    $rows=@($provider.chars)
    foreach ($row in $rows) { foreach ($c in $row.ToCharArray()) { if ([int]$c -ne 0) { if ($codes.ContainsKey([int]$c)) { throw ('Duplicate glyph U+{0:X4}' -f [int]$c) }; $codes[[int]$c]=1 } } }
    $namespace,$path = $provider.file.Split(':')
    if ($namespace -eq 'minecraft') { continue }
    $bitmap = [Drawing.Bitmap]::new((Join-Path $root ('assets/' + $namespace + '/textures/' + $path)))
    try {
        if ($bitmap.Width / $rows[0].Length -gt 256 -or $bitmap.Height / $rows.Count -gt 256) { throw "Glyph cell exceeds the 256 px font page: $path" }
    } finally { $bitmap.Dispose() }
}
foreach ($fontName in @('default','uniform')) {
    $definition = [IO.File]::ReadAllText((Join-Path $root ('assets/minecraft/font/'+$fontName+'.json'))) | ConvertFrom-Json
    if ($definition.providers[0].id -ne 'tilkiinterface:ui') { throw 'Missing font reference' }
}
# The ESC frame is the label of "Back to Game" (its zero net width is checked by the
# build's preview renderer); the language files must carry the generated label.
$properties = [IO.File]::ReadAllText((Join-Path $projectRoot 'src/main/resources/hud-layout.properties'), [Text.Encoding]::UTF8)
$layout = @{}
foreach ($line in $properties -split "`r?`n") {
    if ($line -match '^([^#=]+)=(.*)$') { $layout[$Matches[1]] = [Text.RegularExpressions.Regex]::Unescape(($Matches[2] -replace '\\([:=])','$1')) }
}
foreach ($language in @('tr_tr','en_us','en_gb')) {
    $definition = [IO.File]::ReadAllText((Join-Path $root ('assets/minecraft/lang/'+$language+'.json'))) | ConvertFrom-Json
    if ($definition.'menu.game' -ne '') { throw "Fixed-position ESC title must stay hidden: $language" }
    if ($definition.'menu.returnToGame' -ne $layout["esc.label.$language"]) { throw "ESC frame label differs from the layout: $language" }
}
foreach ($key in @('tab.header.1.1','tab.footer.4.0','tab.post.left.20','tab.post.right.1','sidebar.title.13','sidebar.separator')) { if (!$layout.ContainsKey($key)) { throw "Layout key missing: $key" } }
foreach ($state in @('button','button_highlighted','button_disabled')) {
    $imagePath = Join-Path $root ('assets/minecraft/textures/gui/sprites/widget/'+$state+'.png')
    $bitmap = [Drawing.Bitmap]::new($imagePath)
    try { if ($bitmap.Width -ne 200 -or $bitmap.Height -ne 20) { throw 'GUI button must match the vanilla 200x20 sprite' } } finally { $bitmap.Dispose() }
    $scaling = ([IO.File]::ReadAllText($imagePath+'.mcmeta') | ConvertFrom-Json).gui.scaling
    if ($scaling.type -ne 'nine_slice' -or $scaling.width -ne 200 -or $scaling.height -ne 20 -or $scaling.border.left -ne 7 -or $scaling.border.right -ne 7 -or $scaling.border.top -ne 3 -or $scaling.border.bottom -ne 3) { throw 'GUI button scaling invalid' }
}
foreach ($level in 1..5) {
    $bitmap = [Drawing.Bitmap]::new((Join-Path $root "assets/minecraft/textures/gui/sprites/icon/ping_$level.png"))
    try { if ($bitmap.Width -ne 10 -or $bitmap.Height -ne 8) { throw 'Ping sprites must be 10x8' } } finally { $bitmap.Dispose() }
}
$zipPath = Join-Path $projectRoot 'dist/TilkiInterface-ResourcePack.zip'
$zip = [IO.Compression.ZipFile]::OpenRead($zipPath)
try {
    if (!$zip.GetEntry('pack.mcmeta') -or !$zip.GetEntry('assets/minecraft/lang/tr_tr.json') -or !$zip.GetEntry('assets/tilkiinterface/textures/font/v3/esc_frame_0.png') -or !$zip.GetEntry('assets/tilkiinterface/textures/font/v3/ascii_title.png')) { throw 'ZIP layout invalid' }
    if ($zip.Entries.FullName | Where-Object { $_ -like 'tilki_*/*' -or $_ -like 'assets/tilkiinterface/textures/font/hud/*' -or $_ -like 'assets/tilkiinterface/textures/font/esc_menu/*' }) { throw 'v2 assets remain in ZIP' }
} finally { $zip.Dispose() }
$hash = (Get-FileHash $zipPath -Algorithm SHA1).Hash.ToLowerInvariant()
if ($hash -ne ([IO.File]::ReadAllText((Join-Path $projectRoot 'dist/resourcepack-sha1.txt'))).Trim()) { throw 'Pack SHA1 mismatch' }
$config = [IO.File]::ReadAllText((Join-Path $projectRoot 'src/main/resources/config.yml'))
if (!$config.Contains($hash)) { Write-Warning 'Default config still points at the previous pack (update pack.url/sha1 when releasing).' }
Write-Output "VALID: UI v3 ($($codes.Count) glyph code points), ESC label in 3 languages, TAB/sidebar layout keys, buttons, ping sprites, ZIP and SHA1 $hash."
