    /** Nine-slice: fixed corners, straight sides resampled along their length, empty middle. */
    static BufferedImage nineSlice(BufferedImage src, Rectangle box, int postOuter, int beamOuter, int corner, double factor, double w, double h) {
        int cw = (int)Math.round(corner * factor * TX), W = (int)Math.round(w * TX), H = (int)Math.round(h * TX);
        int marginX = postOuter - box.x, marginY = beamOuter - box.y;
        int sx0 = postOuter, sy0 = beamOuter, sx1 = box.x + box.width - marginX, sy1 = box.y + box.height - marginY;
        BufferedImage out = new BufferedImage(W, H, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = out.createGraphics();
        int[] xs = {sx0, sx0 + corner, sx1 - corner, sx1}, ys = {sy0, sy0 + corner, sy1 - corner, sy1};
        int[] dx = {0, cw, W - cw, W}, dy = {0, cw, H - cw, H};
        for (int j = 0; j < 3; j++) for (int i = 0; i < 3; i++) {
            if (i == 1 && j == 1) continue;
            g.drawImage(scale(crop(src, xs[i], ys[j], xs[i + 1] - xs[i], ys[j + 1] - ys[j]), dx[i + 1] - dx[i], dy[j + 1] - dy[j]), dx[i], dy[j], null);
        }
        g.dispose();
        return out;
    }

