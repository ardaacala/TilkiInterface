    // ------------------------------------------------------------------ image helpers
    static BufferedImage load(String name) throws IOException {
        BufferedImage source = ImageIO.read(SRC.resolve(name).toFile());
        BufferedImage out = new BufferedImage(source.getWidth(), source.getHeight(), BufferedImage.TYPE_INT_ARGB);
        for (int y = 0; y < source.getHeight(); y++) for (int x = 0; x < source.getWidth(); x++) {
            int p = source.getRGB(x, y), a = p >>> 24;
            out.setRGB(x, y, a < 16 ? 0 : a >= 224 ? p | 0xff000000 : p);
        }
        return out;
    }
    static Rectangle bbox(BufferedImage image) {
        int x0 = image.getWidth(), y0 = image.getHeight(), x1 = -1, y1 = -1;
        for (int y = 0; y < image.getHeight(); y++) for (int x = 0; x < image.getWidth(); x++) if ((image.getRGB(x, y) >>> 24) != 0) {
            x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
        }
        return new Rectangle(x0, y0, x1 - x0 + 1, y1 - y0 + 1);
    }
    static BufferedImage crop(BufferedImage image, int x, int y, int w, int h) {
        BufferedImage out = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = out.createGraphics(); g.drawImage(image, -x, -y, null); g.dispose();
        return out;
    }
    static BufferedImage crop(BufferedImage image, Rectangle r) { return crop(image, r.x, r.y, r.width, r.height); }
    static BufferedImage scale(BufferedImage image, int w, int h) { return BuildShared.areaScale(image, Math.max(1, w), Math.max(1, h)); }
    static boolean opaque(BufferedImage image, int x, int y) { return (image.getRGB(x, y) >>> 24) > 64; }
    /** First and last opaque pixel of the run through (x,y) along one axis: the drawn body. */
    static int[] run(BufferedImage image, int x, int y, boolean horizontal) {
        if (!opaque(image, x, y)) throw new IllegalStateException("probe " + x + "," + y + " is transparent");
        int a = horizontal ? x : y, b = a, limit = horizontal ? image.getWidth() : image.getHeight();
        while (a > 0 && opaque(image, horizontal ? a - 1 : x, horizontal ? y : a - 1)) a--;
        while (b < limit - 1 && opaque(image, horizontal ? b + 1 : x, horizontal ? y : b + 1)) b++;
        return new int[]{a, b};
    }
    /** The longest opaque run across a strip at a leaf-free row (vertical strip) or column. */
    static int[] bodyAcross(BufferedImage src, int at, boolean vertical) {
        int[] best = {0, -1};
        int n = vertical ? src.getWidth() : src.getHeight();
        for (int i = 0; i < n; i++) {
            if (!opaque(src, vertical ? i : at, vertical ? at : i)) continue;
            int[] r = run(src, vertical ? i : at, vertical ? at : i, vertical);
            if (r[1] - r[0] > best[1] - best[0]) best = r;
            i = r[1];
        }
        return best;
    }
    /** Leaves, grass, stones and lantern light (the decorations that must never be cut). */
    static boolean decoration(int p) {
        int a = p >>> 24, r = (p >> 16) & 255, g = (p >> 8) & 255, b = p & 255;
        if (a < 64) return false;
        if (g > r + 10 && g > b) return true;
        if (Math.abs(r - g) < 18 && Math.abs(g - b) < 18 && r > 70) return true;
        return r > 220 && g > 180 && b < 140;
    }

    /** A canvas in GUI coordinates (integer origin) at TX texels per pixel. */
    static final class Canvas {
        final int x0, y0; final BufferedImage image; final Graphics2D g;
        Canvas(int x0, int y0, int x1, int y1) {
            this.x0 = x0; this.y0 = y0;
            image = new BufferedImage((x1 - x0) * TX, (y1 - y0) * TX, BufferedImage.TYPE_INT_ARGB);
            g = image.createGraphics();
        }
        int tx(double x) { return (int)Math.round((x - x0) * TX); }
        int ty(double y) { return (int)Math.round((y - y0) * TX); }
        void draw(BufferedImage texture, double x, double y) { g.drawImage(texture, tx(x), ty(y), null); }
        /**
         * Places rectangle r of src, scaled by factor, so that source point (ax,ay) lands on
         * (gx,gy). Sides listed in 'feather' (L,T,R,B) fade over 3 texels: those edges sit on
         * top of an edge strip and the fade hides the joint between the two sources.
         */
        void place(BufferedImage src, Rectangle r, double factor, double ax, double ay, double gx, double gy, String feather) {
            BufferedImage scaled = scale(crop(src, r), (int)Math.round(r.width * factor * TX), (int)Math.round(r.height * factor * TX));
            int w = scaled.getWidth(), h = scaled.getHeight(), f = 3;
            for (int y = 0; y < h; y++) for (int x = 0; x < w; x++) {
                int d = f;
                if (feather.contains("L")) d = Math.min(d, x);
                if (feather.contains("R")) d = Math.min(d, w - 1 - x);
                if (feather.contains("T")) d = Math.min(d, y);
                if (feather.contains("B")) d = Math.min(d, h - 1 - y);
                if (d < f) { int p = scaled.getRGB(x, y); scaled.setRGB(x, y, ((int)((p >>> 24) * (d + 1) / (double)(f + 1)) << 24) | (p & 0xffffff)); }
            }
            g.drawImage(scaled, (int)Math.round((gx - (ax - r.x) * factor - x0) * TX), (int)Math.round((gy - (ay - r.y) * factor - y0) * TX), null);
        }
        void fill(Color color, double x, double y, double w, double h) { g.setColor(color); g.fillRect(tx(x), ty(y), tx(x + w) - tx(x), ty(y + h) - ty(y)); }
        void clear(double x, double y, double w, double h) {
            for (int yy = Math.max(0, ty(y)); yy < Math.min(image.getHeight(), ty(y + h)); yy++)
                for (int xx = Math.max(0, tx(x)); xx < Math.min(image.getWidth(), tx(x + w)); xx++) image.setRGB(xx, yy, 0);
        }
    }

    /** An edge strip (27–30) scaled once so its drawn body has a given thickness. */
    static final class Strip {
        final String name; final boolean vertical; final double factor, lo, hi; final BufferedImage scaled;
        final int period; final boolean[] clean; final int plainStart, plainLength;
        final StringBuilder log = new StringBuilder();
        /** probe: a leaf-free row (vertical strip) or column where the body is measured. */
        Strip(String name, BufferedImage src, boolean vertical, double thickness, int probe) {
            this.name = name; this.vertical = vertical;
            Rectangle b = bbox(src);
            int[] body = bodyAcross(src, probe, vertical);
            factor = thickness / (body[1] - body[0] + 1);
            int acrossStart = vertical ? b.x : b.y, acrossLength = vertical ? b.width : b.height, length = vertical ? src.getHeight() : src.getWidth();
            BufferedImage band = vertical ? crop(src, b.x, 0, b.width, length) : crop(src, 0, b.y, length, b.height);
            int acrossT = (int)Math.round(acrossLength * factor * TX), lengthT = (int)Math.round(length * factor * TX);
            scaled = vertical ? scale(band, acrossT, lengthT) : scale(band, lengthT, acrossT);
            period = lengthT;
            lo = (body[0] - acrossStart) * factor; hi = (body[1] + 1 - acrossStart) * factor;
            // Leaf-free source lines: no decoration and no drawing outside the wood body,
            // with one art pixel (12 source px) of margin on both sides.
            boolean[] line = new boolean[length];
            for (int i = 0; i < length; i++) {
                boolean ok = true;
                for (int j = acrossStart; j < acrossStart + acrossLength && ok; j++) {
                    int p = vertical ? src.getRGB(j, i) : src.getRGB(i, j);
                    if (decoration(p) || ((p >>> 24) > 64 && (j < body[0] - 2 || j > body[1] + 2))) ok = false;
                }
                line[i] = ok;
            }
            boolean[] safe = new boolean[length];
            for (int i = 0; i < length; i++) { boolean ok = true; for (int k = -12; k <= 12 && ok; k++) ok = line[Math.floorMod(i + k, length)]; safe[i] = ok; }
            clean = new boolean[period];
            double perTexel = 1 / (factor * TX);
            for (int t = 0; t < period; t++) {
                boolean ok = true;
                for (int i = (int)(t * perTexel); i < Math.min(length, Math.ceil((t + 1) * perTexel)) && ok; i++) ok = safe[i];
                clean[t] = ok;
            }
            int bestStart = 0, bestLength = 0;
            for (int t = 0; t < period; t++) {
                if (!clean[t] || clean[Math.floorMod(t - 1, period)]) continue;
                int n = 0; while (n < period && clean[(t + n) % period]) n++;
                if (n > bestLength) { bestLength = n; bestStart = t; }
            }
            if (bestLength == 0 && clean[0]) bestLength = period; // entirely plain
            plainStart = bestStart; plainLength = bestLength;
            log.append(String.format(Locale.ROOT, "%s: body %d–%d (source), ×%.4f, period %d texels (%.1f px), longest plain run at %d (+%d texels); leaf-free texels %s",
                name, body[0], body[1], factor, period, period / (double)TX, plainStart, plainLength, cutList()));
        }
        String cutList() {
            StringBuilder out = new StringBuilder(); int start = -1;
            for (int t = 0; t <= period; t++) {
                boolean c = t < period && clean[t];
                if (c && start < 0) start = t;
                if (!c && start >= 0) { out.append(out.length() == 0 ? "" : ", ").append(start).append('–').append(t - 1); start = -1; }
            }
            return out.toString();
        }
        boolean cut(int t) { return clean[Math.floorMod(t, period)] && clean[Math.floorMod(t - 1, period)]; }
        int pixel(int along, int across) { int s = Math.floorMod(along, period); return vertical ? scaled.getRGB(across, s) : scaled.getRGB(s, across); }
        int acrossTexels() { return vertical ? scaled.getWidth() : scaled.getHeight(); }

        /** A strip of exactly 'length' GUI px whose two ends are leaf-free cuts. */
        BufferedImage fill(double length) {
            int n = (int)Math.round(length * TX), across = acrossTexels();
            int bestA = -1, bestD = 0, fitA = -1, fitD = 0;
            for (int a = 0; a < period; a++) {
                if (!cut(a)) continue;
                for (int d = 1; d <= n + period; d++) {
                    if (!cut(a + d)) continue;
                    if (bestA < 0 || Math.abs(n - d) < Math.abs(n - bestD)) { bestA = a; bestD = d; }
                    if (d <= n && d > fitD) { fitA = a; fitD = d; }
                }
            }
            int[] sequence = new int[n];
            boolean stretch = bestA >= 0 && Math.abs(n - bestD) <= 0.06 * n;
            if (stretch) {
                for (int i = 0; i < n; i++) sequence[i] = bestA + (int)((i + 0.5) * bestD / n);
            } else {
                int left = (n - fitD) / 2, plain = Math.max(1, plainLength);
                for (int i = 0; i < n; i++) {
                    if (fitA >= 0 && i >= left && i < left + fitD) sequence[i] = fitA + (i - left);
                    else sequence[i] = plainStart + Math.floorMod(i - left, plain);
                }
            }
            BufferedImage out = vertical ? new BufferedImage(across, n, BufferedImage.TYPE_INT_ARGB) : new BufferedImage(n, across, BufferedImage.TYPE_INT_ARGB);
            for (int i = 0; i < n; i++) for (int j = 0; j < across; j++) {
                int p = pixel(sequence[i], j);
                if (vertical) out.setRGB(j, i, p); else out.setRGB(i, j, p);
            }
            return out;
        }
        /** Draws a fill whose body's outer edge lies on 'outer'; outerIsLow = the outer edge is the left/top side. */
        void draw(Canvas c, double outer, boolean outerIsLow, double from, double length) {
            double offset = outerIsLow ? outer - lo : outer - hi;
            if (vertical) c.draw(fill(length), offset, from); else c.draw(fill(length), from, offset);
        }
        double across() { return acrossTexels() / (double)TX; }
    }

    // ------------------------------------------------------------------ glyphs
    record Tile(char glyph, int x, int width) {}

    /**
     * Splits a canvas into font glyphs of at most 120×127 GUI px. topRelativeToLine is the
     * canvas top relative to the text origin (vanilla draws a glyph's top at origin + 7 - ascent).
     * Tile x is relative to the canvas's left edge.
     */
    static List<Tile> glyphs(String key, BufferedImage image, int topRelativeToLine) throws IOException {
        List<Tile> tiles = new ArrayList<>();
        int maxW = 240, maxH = 254, top = topRelativeToLine * TX;
        for (int ty = 0; ty < image.getHeight(); ty += maxH) {
            int h = Math.min(maxH, image.getHeight() - ty); h += Math.floorMod(-h, TX);
            for (int tx = 0; tx < image.getWidth(); tx += maxW) {
                int w = Math.min(maxW, image.getWidth() - tx); w += Math.floorMod(-w, TX);
                BufferedImage tile = crop(image, tx, ty, w, h);
                boolean empty = true;
                for (int y = 0; y < h && empty; y++) for (int x = 0; x < w; x++) if ((tile.getRGB(x, y) >>> 24) != 0) { empty = false; break; }
                if (empty) continue;
                int ascent = 7 * TX - (top + ty), height = h;
                if (ascent > height) { // a glyph needs ascent <= height: pad tiles that sit above the line
                    BufferedImage padded = new BufferedImage(w, ascent, BufferedImage.TYPE_INT_ARGB);
                    padded.getGraphics().drawImage(tile, 0, 0, null); tile = padded; height = ascent;
                }
                if ((tile.getRGB(w - 1, 0) >>> 24) == 0) tile.setRGB(w - 1, 0, 0x01ffffff); // full advance
                char glyph = nextGlyph++;
                String file = "v3/" + key + "_" + tiles.size() + ".png";
                ImageIO.write(tile, "png", FONT_TEX.resolve(file).toFile());
                providers.add(bitmap("tilkiinterface:font/" + file, height / TX, ascent / TX, glyph));
                font.put(glyph, new Glyph(tile, height / TX, ascent / TX));
                tiles.add(new Tile(glyph, tx / TX, w / TX));
            }
        }
        return tiles;
    }
    static JsonObject bitmap(String file, int height, int ascent, char glyph) {
        JsonObject p = new JsonObject();
        p.addProperty("type", "bitmap"); p.addProperty("file", file); p.addProperty("height", height); p.addProperty("ascent", ascent);
        JsonArray chars = new JsonArray(); chars.add(String.valueOf(glyph)); p.add("chars", chars);
        return p;
    }
    /** "glyph,x,width;..." with x relative to the given origin. */
    static String tileList(List<Tile> tiles, int origin) {
        StringBuilder out = new StringBuilder();
        for (Tile t : tiles) out.append(out.length() == 0 ? "" : ";").append((int)t.glyph()).append(',').append(origin + t.x()).append(',').append(t.width());
        return out.toString();
    }

    // Signed powers of two for pen moves: F000–F007 move left 1..128 px, F008–F00F move right.
    static final char NEG = '', POS = '';
    static void spaces() {
        JsonObject spaces = new JsonObject(); spaces.addProperty("type", "space");
        JsonObject advances = new JsonObject();
        for (int i = 0; i < 8; i++) {
            advances.addProperty(String.valueOf((char)(NEG + i)), -(1 << i)); advances.addProperty(String.valueOf((char)(POS + i)), 1 << i);
            spaceAdvance.put((char)(NEG + i), -(1 << i)); spaceAdvance.put((char)(POS + i), 1 << i);
        }
        spaces.add("advances", advances); providers.add(spaces);
        layout.setProperty("space.negative", String.valueOf((int)NEG));
        layout.setProperty("space.positive", String.valueOf((int)POS));
    }

    /** Glyph strings with absolute pen positions (GUI px from the line origin). */
    static final class Pen {
        final StringBuilder out = new StringBuilder(); int x;
        Pen move(int to) {
            int left = Math.abs(to - x); char base = to < x ? NEG : POS;
            for (int bit = 7; bit >= 0; bit--) while (left >= (1 << bit)) { out.append((char)(base + bit)); left -= 1 << bit; }
            x = to; return this;
        }
        Pen tiles(List<Tile> tiles, int originX) { for (Tile t : tiles) { move(originX + t.x()); out.append(t.glyph()); x += t.width() + 1; } return this; }
        Pen text(String formatted, int width) { out.append(formatted); x += width; return this; }
    }

