/**
 * TilkiCraft interface v3: ESC menu, sidebar HUD and TAB frame built only from the
 * separate design sources in art/source (the full-screen images in
 * art/source/reference are layout references and are never cut).
 *
 * - Sources keep their alpha; near-opaque pixels (alpha >= 224) become opaque, alpha < 16 transparent.
 * - Every piece is box-filtered once from the source with its own factor, chosen so that
 *   wood bodies of corners and edges have the same thickness.
 * - Frame corners are cut from the full frames on leaf-free rows/columns and drawn last.
 * - Straight edges come from the edge strips. A fill only cuts a strip between two
 *   leaf-free lines, so no leaf is ever cut; small length differences are absorbed by
 *   resampling along the strip (at most 6%) or by plain wood at both ends.
 * - No text is baked: titles use the pack font through moved/tinted copies of the ASCII atlas.
 *
 * Font glyph textures are TX texels per GUI pixel; widget sprites are 1x.
 * Usage: BuildUiV3 <hd ascii.png>
 */
