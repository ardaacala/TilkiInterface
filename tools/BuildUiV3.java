    static String shifted(String text, char base) {
        StringBuilder out = new StringBuilder();
        for (char ch : text.toCharArray()) out.append(ch == ' ' ? String.valueOf((char)(POS + 2)) : String.valueOf((char)(base + ch)));
        return out.toString();
    }
    /** The pack's ASCII atlas at another height on the line (same texture, same advances). */
    static void movedFont(char base, int ascent) {
        providers.add(asciiProvider("minecraft:font/ascii.png", base, 8, ascent));
        asciiFonts.add(new AsciiFont(base, ascent, 0xFFFFFF));
    }
    /** ASCII glyphs raised above the line: cells padded below (a glyph needs ascent <= height), tinted cream. */
    static void raisedFont(char base, int ascent, int tint) throws IOException {
        int cell = atlas.getWidth() / 16, texelsPerPixel = cell / 8, pad = Math.max(0, ascent - 8), cellH = cell + pad * texelsPerPixel;
        BufferedImage raised = new BufferedImage(atlas.getWidth(), cellH * 16, BufferedImage.TYPE_INT_ARGB);
        for (int row = 0; row < 16; row++) for (int y = 0; y < cell; y++) for (int x = 0; x < atlas.getWidth(); x++) {
            int p = atlas.getRGB(x, row * cell + y);
            if ((p >>> 24) == 0) continue;
            int r = ((p >> 16) & 255) * ((tint >> 16) & 255) / 255, g = ((p >> 8) & 255) * ((tint >> 8) & 255) / 255, b = (p & 255) * (tint & 255) / 255;
            raised.setRGB(x, row * cellH + y, (p & 0xff000000) | r << 16 | g << 8 | b);
        }
        ImageIO.write(raised, "png", FONT_TEX.resolve("v3/ascii_title.png").toFile());
        providers.add(asciiProvider("tilkiinterface:font/v3/ascii_title.png", base, 8 + pad, ascent));
        asciiFonts.add(new AsciiFont(base, ascent, tint));
    }
    static JsonObject asciiProvider(String file, char base, int height, int ascent) {
        JsonObject p = new JsonObject();
        p.addProperty("type", "bitmap"); p.addProperty("file", file); p.addProperty("height", height); p.addProperty("ascent", ascent);
        JsonArray rows = new JsonArray();
        for (int row = 0; row < 16; row++) {
            StringBuilder s = new StringBuilder();
            for (int col = 0; col < 16; col++) { int code = row * 16 + col; s.append(code > 32 && code < 127 ? (char)(base + code) : (char)0); }
            rows.add(s.toString());
        }
        p.add("chars", rows);
        return p;
    }

    // ------------------------------------------------------------------ font and packaging
    static void writeFont() throws IOException {
        // Keep the logo glyph and its spaces from the earlier font (used by other modules).
        Path uiJson = ROOT.resolve("assets/tilkiinterface/font/ui.json");
        JsonArray kept = new JsonArray();
        if (Files.exists(uiJson)) for (JsonElement e : JsonParser.parseString(Files.readString(uiJson)).getAsJsonObject().getAsJsonArray("providers")) {
            JsonObject p = e.getAsJsonObject();
            if (p.has("file") && p.get("file").getAsString().equals("tilkiinterface:font/logo.png")) kept.add(p);
            if (p.get("type").getAsString().equals("space") && !p.getAsJsonObject("advances").keySet().isEmpty()
                && p.getAsJsonObject("advances").keySet().stream().allMatch(k -> k.charAt(0) >= 0xEA04 && k.charAt(0) <= 0xEA18)) kept.add(p);
        }
        JsonArray all = new JsonArray(); all.addAll(kept); all.addAll(providers);
        JsonObject root = new JsonObject(); root.add("providers", all);
        Files.writeString(uiJson, new GsonBuilder().disableHtmlEscaping().create().toJson(root));
        // Earlier designs (cut from layout screenshots or drawn in code) are removed, with the
        // 26.2+ overlay that only swapped the old ESC frame (the new frame needs no icon-row holes).
        Files.writeString(ROOT.resolve("pack.mcmeta"),
            "{\"pack\":{\"description\":\"TilkiCraft - forest fox interface | 1.21.4 - 26.x\",\"pack_format\":46,\"supported_formats\":[46,999],\"min_format\":46,\"max_format\":999}}");
        for (Path dir : List.of(FONT_TEX.resolve("hud"), FONT_TEX.resolve("esc_menu"), ROOT.resolve("tilki_icon_menu"), ROOT.resolve("tilki_legacy"))) {
            if (Files.isDirectory(dir)) try (var files = Files.walk(dir)) { for (Path f : files.sorted(Comparator.reverseOrder()).toList()) Files.delete(f); }
        }
        try (var files = Files.list(FONT_TEX)) {
            for (Path f : files.toList()) if (Files.isRegularFile(f) && f.getFileName().toString().matches("icon_.*\\.png|sidebar_logo\\.png")) Files.delete(f);
        }
    }
    static void writeZip() throws Exception {
        Path zip = Path.of("dist/TilkiInterface-ResourcePack.zip");
        Files.createDirectories(zip.getParent());
        try (ZipOutputStream out = new ZipOutputStream(Files.newOutputStream(zip)); var files = Files.walk(ROOT)) {
            for (Path file : files.filter(Files::isRegularFile).sorted().toList()) {
                ZipEntry entry = new ZipEntry(ROOT.relativize(file).toString().replace('\\', '/'));
                entry.setTime(0); out.putNextEntry(entry); Files.copy(file, out); out.closeEntry();
            }
        }
        String hash = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-1").digest(Files.readAllBytes(zip)));
        Files.writeString(Path.of("dist/resourcepack-sha1.txt"), hash + "\n");
        System.out.println("UI v3 pack SHA1: " + hash + "; " + Files.size(zip) + " bytes");
    }
