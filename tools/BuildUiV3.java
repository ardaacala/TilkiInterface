    static String rect(Rectangle r) { return r.x + "," + r.y + " " + r.width + "×" + r.height; }
    static BufferedImage buttonSprite(BufferedImage source) {
        BufferedImage cut = crop(source, bbox(source));
        double factor = 20.0 / cut.getHeight();
        int end = 7, endSrc = (int)Math.round(end / factor), middleSrc = cut.getWidth() - 2 * endSrc;
        BufferedImage out = new BufferedImage(200, 20, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = out.createGraphics();
        g.drawImage(scale(crop(cut, 0, 0, endSrc, cut.getHeight()), end, 20), 0, 0, null);
        g.drawImage(scale(crop(cut, endSrc, 0, middleSrc, cut.getHeight()), 200 - 2 * end, 20), end, 0, null);
        g.drawImage(scale(crop(cut, cut.getWidth() - endSrc, 0, endSrc, cut.getHeight()), end, 20), 200 - end, 0, null);
        g.dispose();
        return out;
    }

